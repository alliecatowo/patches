#!/usr/bin/env node
// Copies a curated set of markdown docs from ../docs into ./docs (gitignored) with a
// generated VitePress frontmatter block, so the site always mirrors whatever's currently
// in docs/ instead of forking a second copy that drifts. Runs as a `pre`-step of both
// `dev` and `build` (see package.json). VitePress's `srcDir` can only point at one
// directory, so this local copy is the workaround (P9-001 brief).
//
// Source docs are owned by other agents working concurrently — a missing file is logged
// and skipped rather than failing the build.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const siteRoot = join(here, '..');
const repoRoot = join(siteRoot, '..');
const outRoot = join(siteRoot, 'docs');

/** @type {Array<{ src: string, dest: string, title: string }>} */
const MANIFEST = [
  { src: 'docs/user-guide.md', dest: 'guide/index.md', title: 'Guide' },
  {
    src: 'docs/architecture/overview.md',
    dest: 'architecture/overview.md',
    title: 'Architecture overview',
  },
  {
    src: 'docs/architecture/federation.md',
    dest: 'architecture/federation.md',
    title: 'Federation',
  },
  { src: 'docs/architecture/pages.md', dest: 'architecture/pages.md', title: 'Patches Pages' },
  { src: 'docs/product/principles.md', dest: 'product/principles.md', title: 'Product principles' },
  { src: 'docs/product/roadmap.md', dest: 'product/roadmap.md', title: 'Roadmap' },
  { src: 'docs/product/moderation.md', dest: 'product/moderation.md', title: 'Moderation' },
  { src: 'docs/product/privacy.md', dest: 'product/privacy.md', title: 'Privacy' },
  { src: 'docs/operations/deployment.md', dest: 'operations/deployment.md', title: 'Deployment' },
  {
    src: 'docs/operations/federation.md',
    dest: 'operations/federation.md',
    title: 'Federation lab',
  },
];

/**
 * @param {string} title
 */
function frontmatter(title) {
  return `---\ntitle: ${JSON.stringify(title)}\n---\n\n<!-- Generated by site/scripts/sync-docs.mjs from the repo's docs/ — edit the source there, not this file. -->\n\n`;
}

// CommonMark allows an inline code span (`` `...` ``) to spread across a soft line break —
// the source docs use this (e.g. "`--user\n<id>`"). VitePress renders markdown through
// markdown-it and then re-parses the result as a Vue SFC template; in that second pass a
// code span split across lines isn't recognized, so its contents (here `<id>`) leak through
// as unescaped-looking HTML and the Vue compiler errors with "Element is missing end tag."
// This is a site-side rendering quirk, not a doc-authoring mistake, so it's fixed here at
// sync time (site/** is this task's file set; docs/** is not) by joining any inline code
// span that spans a line break onto one line, outside of fenced code blocks.
function collapseMultilineCodeSpans(markdown) {
  const lines = markdown.split('\n');
  const out = [];
  let inFence = false;
  let fenceMarker = '';
  let spanBuffer = null;

  for (const line of lines) {
    const trimmed = line.trim();
    const fenceMatch = /^(`{3,}|~{3,})/.exec(trimmed);

    if (spanBuffer === null && fenceMatch) {
      if (!inFence) {
        inFence = true;
        fenceMarker = fenceMatch[1][0];
      } else if (trimmed.startsWith(fenceMarker.repeat(3))) {
        inFence = false;
      }
      out.push(line);
      continue;
    }

    if (inFence) {
      out.push(line);
      continue;
    }

    if (spanBuffer !== null) {
      spanBuffer += ' ' + line;
      if ((line.match(/`/g) ?? []).length % 2 === 1) {
        out.push(spanBuffer);
        spanBuffer = null;
      }
      continue;
    }

    if ((line.match(/`/g) ?? []).length % 2 === 1) {
      spanBuffer = line;
      continue;
    }

    out.push(line);
  }

  // Unterminated span (shouldn't happen in well-formed markdown) — flush as-is rather
  // than dropping content.
  if (spanBuffer !== null) out.push(spanBuffer);

  return out.join('\n');
}

mkdirSync(outRoot, { recursive: true });

let copied = 0;
let skipped = 0;

for (const entry of MANIFEST) {
  const srcPath = join(repoRoot, entry.src);
  if (!existsSync(srcPath)) {
    console.warn(`[sync-docs] skipping missing source: ${entry.src}`);
    skipped += 1;
    continue;
  }

  const destPath = join(outRoot, entry.dest);
  mkdirSync(dirname(destPath), { recursive: true });

  const raw = readFileSync(srcPath, 'utf8');
  writeFileSync(destPath, frontmatter(entry.title) + collapseMultilineCodeSpans(raw));
  copied += 1;
}

console.log(`[sync-docs] copied ${copied} doc(s) into site/docs/ (${skipped} skipped)`);
