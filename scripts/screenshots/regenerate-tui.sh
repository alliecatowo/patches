#!/usr/bin/env bash
# Fixes #305 — regenerates docs/media/tui/frames.md from the committed golden-frame fixtures
# (apps/tui/test/golden/*.txt, produced by apps/tui/test/golden.test.tsx). There is no PNG/SVG
# renderer for Ink frames in this repo and this script adds no new dependency to make one
# (CLAUDE.md hard rule); instead it embeds each frame as a fenced text block, byte-for-byte
# identical to what CI's golden-frame test asserts against, so README media never drifts from
# what the TUI actually renders.
#
# Regenerate the source fixtures first if the TUI's visual output changed:
#   UPDATE_GOLDEN=1 pnpm --filter @patches/tui test -- golden
# Then re-run this script to refresh docs/media/tui/frames.md.
#
# Usage: mise run screenshots:tui  (or run this script directly from the repo root)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

GOLDEN_DIR="apps/tui/test/golden"
OUT="docs/media/tui/frames.md"
mkdir -p "$(dirname "$OUT")"

{
  echo "<!-- Generated by scripts/screenshots/regenerate-tui.sh from apps/tui/test/golden/*.txt — do not hand-edit. -->"
  echo "# TUI golden frames"
  echo
  echo "Byte-for-byte captures from \`apps/tui/test/golden.test.tsx\` (\`FakeApiHandle\`, frozen"
  echo "clock, two committed geometries: \`100x30\` and \`140x40\`). These are the same frames CI"
  echo "diffs on every PR, so they can never go stale silently — a visual change that isn't"
  echo "reflected here fails \`pnpm --filter @patches/tui test -- golden\` first."
  echo
  for file in "$GOLDEN_DIR"/*.txt; do
    name="$(basename "$file" .txt)"
    echo "## ${name}"
    echo
    echo '```text'
    cat "$file"
    echo '```'
    echo
  done
} > "$OUT"

frame_count="$(find "$GOLDEN_DIR" -maxdepth 1 -name '*.txt' | wc -l)"
echo "==> Wrote $OUT from $frame_count golden frames."
